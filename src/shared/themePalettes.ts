export function getThemeColorsForAppearance(
  theme: ThemeDefinition,
  appearance: ThemeAppearance
): ThemeColors | null {
  if (theme.appearance === appearance) return theme.colors;
  return theme.variants?.[appearance] ?? null;
}

export function getThemeDefinition(id: string): ThemeDefinition | null {
  if (id === 'default' || id === 'atlas') return ATLAS_THEME;
  return BUILT_IN_THEMES.find((t) => t.id === id) ?? null;
}

export function getThemeModes(theme: ThemeDefinition): ReadonlyArray<ThemeAppearance> {
  const modes: ThemeAppearance[] = [theme.appearance];
  if (theme.variants?.light && !modes.includes('light')) modes.push('light');
  if (theme.variants?.dark && !modes.includes('dark')) modes.push('dark');
  return modes;
}

