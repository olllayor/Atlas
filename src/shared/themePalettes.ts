export function parseThemeFile(raw: unknown): ThemeDefinition {
  if (!raw || typeof raw !== 'object') {
    throw new Error('Theme definition must be a valid JSON object');
  }
  const obj = raw as Record<string, unknown>;
  const label =
    typeof obj.label === 'string' && obj.label.trim()
      ? obj.label.trim()
      : typeof obj.name === 'string' && obj.name.trim()
        ? obj.name.trim()
        : 'Custom Theme';
  const id =
    typeof obj.id === 'string' && obj.id.trim()
      ? obj.id.trim().toLowerCase().replace(/[^a-z0-9-]/g, '-')
      : label.toLowerCase().replace(/[^a-z0-9-]/g, '-');
  const appearance: ThemeAppearance = obj.appearance === 'light' ? 'light' : 'dark';

  if (!obj.colors || typeof obj.colors !== 'object') {
    throw new Error('Theme is missing a colors object');
  }

  const rawColors = obj.colors as Record<string, string>;
  const baseColors = appearance === 'light' ? ATLAS_LIGHT_THEME_COLORS : ATLAS_DARK_THEME_COLORS;
  const colors = { ...baseColors, ...rawColors } as ThemeColors;

  let variants: ThemeVariants | undefined = undefined;
  if (obj.variants && typeof obj.variants === 'object') {
    const rawVariants = obj.variants as Record<string, Record<string, string>>;
    variants = {};
    if (rawVariants.light && typeof rawVariants.light === 'object') {
      variants = { ...variants, light: { ...ATLAS_LIGHT_THEME_COLORS, ...rawVariants.light } as ThemeColors };
    }
    if (rawVariants.dark && typeof rawVariants.dark === 'object') {
      variants = { ...variants, dark: { ...ATLAS_DARK_THEME_COLORS, ...rawVariants.dark } as ThemeColors };
    }
  }

  const collection =
    obj.collection && typeof obj.collection === 'object' && typeof (obj.collection as any).id === 'string'
      ? { id: String((obj.collection as any).id), label: String((obj.collection as any).label || (obj.collection as any).id) }
      : undefined;

  return {
    id,
    label,
    appearance,
    colors,
    variants,
    collection,
    ...(obj.sidebarArtwork !== undefined ? { sidebarArtwork: Boolean(obj.sidebarArtwork) } : {}),
    ...(obj.managed !== undefined ? { managed: Boolean(obj.managed) } : {}),
  };
}

export const THEME_FILE_VERSION = 1 as const;

export function serializeThemeFile(theme: ThemeDefinition): string {
  return JSON.stringify(
    {
      version: THEME_FILE_VERSION,
      id: theme.id,
      name: theme.label,
      appearance: theme.appearance,
      colors: theme.colors,
      ...(theme.variants ? { variants: theme.variants } : {}),
      ...(theme.collection ? { collection: theme.collection } : {}),
      ...(theme.sidebarArtwork !== undefined ? { sidebarArtwork: theme.sidebarArtwork } : {}),
      ...(theme.managed !== undefined ? { managed: theme.managed } : {}),
    },
    null,
    2,
  );
}
